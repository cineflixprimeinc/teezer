import * as SecureStore from "expo-secure-store";
import { AppAttestNative } from "../../modules/app-attest";
import { api } from "@/api/client";

/**
 * App Attest, from the app's side.
 *
 * One place owns the whole lifecycle - support detection, the key, attestation,
 * and producing per-request assertions - so no screen ever touches
 * DCAppAttestService directly and there is a single place to reason about what
 * happens when any of it fails.
 *
 * ── What is and is not stored ───────────────────────────────────────────────
 * Only the key IDENTIFIER is persisted, in the Keychain. The private key itself
 * is generated by iOS in the Secure Enclave and cannot be exported by anyone,
 * this app included - that is the entire security property, and it is why there
 * is no .p8 or any other credential anywhere in this bundle. The server remains
 * the authority on whether a key has actually been attested; the local
 * `attested` flag below is a cache to avoid re-attesting on every launch, never
 * a claim the server trusts.
 *
 * ── Failure is always soft ──────────────────────────────────────────────────
 * Unsupported device, no network, Apple's attestation service down, a key the
 * system has forgotten: every one of these resolves to "no headers", and the
 * request proceeds under the app's existing authentication. The server decides
 * whether that is acceptable per endpoint. Nothing here ever blocks startup,
 * navigation, the feed or playback.
 */

const KEY_ID_STORE = "teezer_appattest_key_id";
const ATTESTED_STORE = "teezer_appattest_attested";

/** In-memory mirror so the common path does not hit the Keychain every request. */
let cachedKeyId: string | null = null;
let attested = false;
let bootstrapped = false;

/** De-duplicates concurrent bootstraps - several protected requests can fire at once. */
let inFlight: Promise<boolean> | null = null;

export function isAppAttestSupported(): boolean {
  try {
    return AppAttestNative?.isSupported() ?? false;
  } catch {
    return false;
  }
}

/**
 * Ensure this install has an attested key, doing the minimum work needed.
 *
 * Safe to call repeatedly and from several places at once: the first call does
 * the work and every concurrent caller awaits the same promise. Returns whether
 * attestation is usable, so callers can skip straight past when it is not.
 */
export async function ensureAttested(): Promise<boolean> {
  if (attested && cachedKeyId) return true;
  if (!isAppAttestSupported()) return false;
  if (inFlight) return inFlight;

  inFlight = bootstrap().finally(() => { inFlight = null; });
  return inFlight;
}

async function bootstrap(): Promise<boolean> {
  try {
    if (!bootstrapped) {
      cachedKeyId = await SecureStore.getItemAsync(KEY_ID_STORE);
      attested = (await SecureStore.getItemAsync(ATTESTED_STORE)) === "1";
      bootstrapped = true;
    }
    if (attested && cachedKeyId) return true;

    // Reuse an existing key if we have one. A new key per attempt would burn
    // through Apple's attestation rate limit and orphan a Secure Enclave key
    // on every failure - Apple's guidance is explicitly to retry with the same
    // key rather than generate another.
    if (!cachedKeyId) {
      cachedKeyId = await AppAttestNative!.generateKey();
      await SecureStore.setItemAsync(KEY_ID_STORE, cachedKeyId);
    }

    const challenge = await fetchChallenge("attest");
    if (!challenge) return false;

    const attestation = await AppAttestNative!.attestKey(cachedKeyId, challenge);

    await api.post("/app-attest/key", {
      key_id: cachedKeyId,
      attestation,
      challenge,
    });

    attested = true;
    await SecureStore.setItemAsync(ATTESTED_STORE, "1");
    return true;
  } catch {
    // Left un-attested; the next protected request tries again. Deliberately
    // no backoff state machine - attestation is attempted at most once per
    // protected request, which is already self-limiting.
    return false;
  }
}

/** Ask the server for a single-use challenge. Null when unavailable or dark. */
async function fetchChallenge(purpose: "attest" | "assert"): Promise<string | null> {
  try {
    const res = await api.post("/app-attest/challenge", { purpose });
    const data = res.data?.data;
    if (!data?.available) return null;
    return typeof data.challenge === "string" ? data.challenge : null;
  } catch {
    return null;
  }
}

/**
 * Headers proving this specific request came from this attested install.
 *
 * The signed client data binds the assertion to the method, the path and a
 * digest of the body, so one captured from a harmless request cannot be
 * replayed onto a withdrawal. It must match the server's own composition
 * exactly - see AssertionVerifier::clientData.
 *
 * Returns an empty object on every failure path, which is what makes this safe
 * to call unconditionally from the API client.
 */
export async function attestHeaders(
  method: string,
  path: string,
  bodyDigest: string,
): Promise<Record<string, string>> {
  if (!(await ensureAttested()) || !cachedKeyId) return {};

  try {
    const challenge = await fetchChallenge("assert");
    if (!challenge) return {};

    const clientData = [method.toUpperCase(), path, bodyDigest, challenge].join("|");
    const assertion = await AppAttestNative!.generateAssertion(cachedKeyId, clientData);

    return {
      "X-App-Attest-Key-Id": cachedKeyId,
      "X-App-Attest-Assertion": assertion,
      "X-App-Attest-Challenge": challenge,
    };
  } catch {
    // A key iOS no longer recognises (restored device, key invalidated) lands
    // here. Drop the local attestation so the next call re-attests instead of
    // retrying a key that will never work again.
    attested = false;
    void SecureStore.deleteItemAsync(ATTESTED_STORE).catch(() => {});
    return {};
  }
}

/**
 * Forget this install's attestation state.
 *
 * NOT called on sign-out: the key is an app-instance identity, not a user's,
 * and one handset legitimately serves several saved accounts here - throwing it
 * away on every logout would re-attest constantly and hit Apple's rate limit
 * for no benefit. Exposed for the reinstall/restore path and for support.
 */
export async function resetAppAttest(): Promise<void> {
  cachedKeyId = null;
  attested = false;
  bootstrapped = false;
  await SecureStore.deleteItemAsync(KEY_ID_STORE).catch(() => {});
  await SecureStore.deleteItemAsync(ATTESTED_STORE).catch(() => {});
}
